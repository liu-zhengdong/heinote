import { createHash } from "node:crypto";
import type { Express, NextFunction, Request, Response } from "express";
import { agentApiMd, llmsTxt, skillMd } from "./agent-onboarding-content.ts";

/**
 * UC-52: public agent self-onboarding. An agent that only knows the site URL
 * can fetch /llms.txt for the guide, /api/v1/skill.md for the installable
 * skill (guide + embedded helper script) and /api/v1/agent-api.md for the
 * contract — all anonymous, since the requester holds no credentials by
 * design (the UC-41 auth-request flow issues the token afterwards).
 *
 * Content is embedded at build time (generated by
 * scripts/gen-agent-onboarding.mjs): the runtime package carries no docs/ or
 * skills/ directories, so reading from disk is not an option. Embedded
 * content is constant for the life of the process, so each document gets a
 * stable weak ETag and conditional requests return 304.
 */

const docs: { path: string; body: string }[] = [
  { path: "/llms.txt", body: llmsTxt },
  { path: "/api/v1/skill.md", body: skillMd },
  { path: "/api/v1/agent-api.md", body: agentApiMd },
];

const etag = (body: string) => `W/"${createHash("sha256").update(body).digest("hex").slice(0, 32)}"`;

const sendMarkdown = (req: Request, res: Response, body: string, tag: string) => {
  res.set({
    "Content-Type": "text/markdown; charset=utf-8",
    ETag: tag,
    // Revalidate each time: the doc is cheap, and a redeployed build must
    // not keep serving the previous process's snapshot.
    "Cache-Control": "no-cache",
    Link: '</llms.txt>; rel="describedby"',
  });
  if (req.headers["if-none-match"] === tag) return res.status(304).end();
  res.send(body);
};

// Negotiate "/" between browsers and programmatic clients (curl, fetch, AI
// WebFetch). Browsers send `text/html` without `text/markdown`; clients that
// omit `text/html`, reject it (`q=0`), or prefer `text/markdown` (e.g.
// `Accept: text/markdown, text/html;q=0.8`) receive the onboarding markdown
// directly instead of the SPA shell.
const prefersHtml = (accept: string | undefined): boolean => {
  let htmlQ = -1;
  let mdQ = -1;
  for (const part of (accept ?? "").split(",")) {
    const [rawType, ...params] = part.split(";");
    const type = rawType?.trim().toLowerCase();
    if (type !== "text/html" && type !== "application/xhtml+xml" && type !== "text/markdown") continue;
    let q = 1;
    let valid = true;
    for (const param of params) {
      const match = /^\s*q\s*=\s*(.+?)\s*$/i.exec(param);
      if (!match) continue;
      if (!/^(?:1(?:\.0{0,3})?|0(?:\.\d{0,3})?)$/.test(match[1])) { valid = false; break; }
      q = Number(match[1]);
    }
    if (!valid) continue;
    if (type === "text/markdown") mdQ = Math.max(mdQ, q);
    else htmlQ = Math.max(htmlQ, q);
  }
  return htmlQ > 0 && htmlQ > mdQ;
};

export function attachAgentOnboarding(app: Express): void {
  for (const { path, body } of docs) {
    const tag = etag(body);
    app.get(path, (req: Request, res: Response) => sendMarkdown(req, res, body, tag));
  }
  const tag = etag(llmsTxt);
  app.get("/", (req: Request, res: Response, next: NextFunction) => {
    // The two representations of "/" must never be coalesced by a shared cache,
    // and even the HTML shell advertises the onboarding guide via Link header.
    res.vary("Accept");
    res.set("Link", '</llms.txt>; rel="describedby"');
    if (prefersHtml(req.headers.accept)) return next();
    sendMarkdown(req, res, llmsTxt, tag);
  });
}
