import { createHash } from "node:crypto";
import type { Express, Request, Response } from "express";
import { agentApiMd, llmsTxt, skillMd } from "./agent-onboarding-content.ts";

/**
 * UC-52: public agent self-onboarding. An agent that only knows the site URL
 * can fetch /llms.txt for the guide, /api/v1/skill.md for the installable
 * skill (guide + embedded helper script) and /api/v1/agent-api.md for the
 * contract — all anonymous, since the requester holds no credentials by
 * design (the UC-41 auth-request flow issues the token afterwards).
 *
 * Content is embedded at build time (generated by
 * scripts/gen-agent-onboarding.mjs): the runtime package carries no docs/ or
 * skills/ directories, so reading from disk is not an option. Embedded
 * content is constant for the life of the process, so each document gets a
 * stable weak ETag and conditional requests return 304.
 */

const docs: { path: string; body: string }[] = [
  { path: "/llms.txt", body: llmsTxt },
  { path: "/api/v1/skill.md", body: skillMd },
  { path: "/api/v1/agent-api.md", body: agentApiMd },
];

const etag = (body: string) => `W/"${createHash("sha256").update(body).digest("hex").slice(0, 32)}"`;

export function attachAgentOnboarding(app: Express): void {
  for (const { path, body } of docs) {
    const tag = etag(body);
    app.get(path, (req: Request, res: Response) => {
      res.set({
        "Content-Type": "text/markdown; charset=utf-8",
        ETag: tag,
        // Revalidate each time: the doc is cheap, and a redeployed build must
        // not keep serving the previous process's snapshot.
        "Cache-Control": "no-cache",
        Link: '</llms.txt>; rel="describedby"',
      });
      if (req.headers["if-none-match"] === tag) return res.status(304).end();
      res.send(body);
    });
  }
}
